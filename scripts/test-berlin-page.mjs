import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {eligible,render} from "./build-berlin-page.mjs";
const day="2026-11-23";
const base={id:"berlin-test-1",country:"DE",city:"Berlin",date:day,title:"Quellenbestätigte Versammlung",start:"13:00",source:"Amtliche Quelle",source_url:"https://www.berlin.de/polizei/service/versammlungsbehoerde/versammlungen-aufzuege/index.php/index/all.json?q="};
assert.equal(eligible(base,day),true);
assert.equal(eligible({...base,city:"Frankfurt"},day),false);
assert.equal(eligible({...base,date:"2026-11-22"},day),false);
assert.equal(eligible({...base,status_code:"cancelled"},day),false);
assert.equal(eligible({...base,event_status:"Abgesagt"},day),false);
const html=render([base,{...base,id:"duplicate"},{...base,id:"past",date:"2026-11-22"},{...base,id:"cancel",status_code:"cancelled"},{...base,id:"foreign",city:"Frankfurt"}],day);
assert.ok(html.includes("<h1>Demonstrationen in Berlin</h1>"));
assert.ok(html.includes('rel="canonical" href="https://demoradar.pages.dev/berlin/"'));
assert.ok(html.includes('name="description"'));
assert.ok(html.includes('href="https://www.berlin.de/polizei/service/versammlungsbehoerde/versammlungen-aufzuege/"'));
assert.ok(html.includes('href="/?event=berlin-test-1#eventDetail"'));
assert.ok(html.includes("1 unterschiedliche kommende Quelleneinträge"));
assert.ok(!html.includes("Frankfurt"));
assert.ok(!html.includes("2026-11-22"));
assert.ok(!html.includes("application/ld+json"));
assert.ok(!html.includes("all.json"));
const unsafe=render([{...base,source_url:"javascript:alert(1)"}],day);
assert.ok(unsafe.includes("Amtliche Quelle"));
assert.ok(!unsafe.includes("javascript:"));
const actual=readFileSync("berlin/index.html");
assert.ok(actual.includes("<h1>Demonstrationen in Berlin</h1>"));
assert.ok(readFileSync("sitemap.xml","utf8").includes("<loc>https://demoradar.pages.dev/berlin/</loc>"));
console.log("Berlin static SEO page verified");
