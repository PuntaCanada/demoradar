import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {classify,verify} from "./check-publication-after-refresh.mjs";
const sample=(a,b)=>'"status": "'+a+'"\nPUBLIC FUTURE PROVENANCE REPORT: '+JSON.stringify({status:b});
assert.equal(classify(sample("exact_dataset_match","exact_future_report_match")),"matched");
assert.equal(classify(sample("dataset_differs","exact_future_report_match")),"mismatch");
assert.equal(classify(sample("exact_dataset_match","future_report_differs")),"mismatch");
assert.equal(classify(sample("not_verified","exact_future_report_match")),"unavailable");
assert.equal(classify("garbled output"),"unavailable");
let calls=0,waits=0;
assert.equal(await verify({run:async()=>({ok:true,output:sample(++calls===3?"exact_dataset_match":"dataset_differs","exact_future_report_match")}),wait:async()=>{waits++},attempts:4}),"matched");
assert.equal(calls,3);assert.equal(waits,2);
calls=0;waits=0;
assert.equal(await verify({run:async()=>{calls++;return {ok:false,output:""}},wait:async()=>{waits++},attempts:3}),"unavailable");
assert.equal(calls,3);assert.equal(waits,2);
const workflow=readFileSync(".github/workflows/update-events.yml","utf8");
assert.ok(workflow.indexOf("node scripts/test-publication-after-refresh.mjs")<workflow.indexOf("node scripts/check-source-admission.mjs"));
assert.ok(workflow.lastIndexOf("node scripts/check-publication-after-refresh.mjs")>workflow.lastIndexOf('git push'));
console.log("Post-refresh publication probe: deterministic retry and state regressions passed");
