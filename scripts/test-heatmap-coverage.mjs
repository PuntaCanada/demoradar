import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const data=JSON.parse(readFileSync("data/state-source-coverage.json","utf8"));
const geo=JSON.parse(readFileSync("data/germany-states.json","utf8"));
assert.equal(data.version,1);
assert.equal(data.states.length,16);
assert.deepEqual(new Set(data.states.map(s=>s.state)),new Set(geo.states.map(s=>s.name)));
assert.ok(data.states.every(s=>["regional_partial","local_partial","no_confirmed_regular_feed"].includes(s.status)));
assert.ok(data.states.every(s=>typeof s.scope==="string"&&s.scope.length>20));
assert.ok(data.states.every(s=>s.url===null||/^https:\/\//.test(s.url)));
assert.equal(data.states.find(s=>s.state==="Berlin").status,"regional_partial");
assert.equal(data.states.find(s=>s.state==="Nordrhein-Westfalen").status,"local_partial");
assert.equal(data.states.find(s=>s.state==="Hamburg").status,"no_confirmed_regular_feed");
const source=readFileSync("heatmap.js","utf8");
const de=readFileSync("index.html","utf8"),en=readFileSync("en/index.html","utf8"),i18n=readFileSync("i18n.js","utf8");
assert.ok(source.includes('fetch("/data/state-source-coverage.json"'));
assert.ok(source.includes("zeroLabel(item.state,0)"));
assert.ok(source.includes('stroke-dasharray'));
assert.ok(source.includes("sourceLabel(item.state)"));
assert.ok(de.includes('data-i18n="map.coverageNote"')&&en.includes('data-i18n="map.coverageNote"'));
for(const key of ["map.zeroGap","map.zeroReported","map.sourceRegional","map.sourceLocal","map.sourceMissing","map.coverageNote"])assert.equal(i18n.split('"'+key+'"').length,3,"DE and EN translations: "+key);
console.log("Heatmap source coverage: 16 states, three provenance classes, zero-gap handling and bilingual UI OK.");
